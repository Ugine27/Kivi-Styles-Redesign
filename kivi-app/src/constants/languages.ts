export function getSanitizedDialLanguages(): string[] {
  try {
    const saved = localStorage.getItem('whispurr_dial_languages');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) {
        const mapped = parsed
          .map((p: string) => {
            if (ALL_DIAL_LANGUAGES.includes(p)) return p;
            const match = ALL_DIAL_LANGUAGES.find(l => l.startsWith(p + ' ') || l.split(' — ')[0] === p);
            return match;
          })
          .filter(Boolean) as string[];
        if (mapped.length > 0) return mapped;
      }
    }
  } catch (e) {}
  return DEFAULT_DIAL_LANGUAGES;
}
